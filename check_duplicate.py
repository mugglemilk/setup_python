print("=== คำที่ซ้ำกับ dataset ===")
duplicate_groups = []
unique_groups = []

for word_list in seed_data:
    overlap = [w for w in word_list if w in dataset_words]
    unique = [w for w in word_list if w not in dataset_words]
    if overlap:
        duplicate_groups.append((word_list[0], overlap, unique))
    else:
        unique_groups.append(word_list[0])

for head, overlap, unique in duplicate_groups:
    print(f"\nกลุ่ม '{head}'")
    print(f"  ซ้ำ: {overlap}")
    print(f"  ไม่ซ้ำ: {unique}")

print(f"\n=== กลุ่มที่ไม่ซ้ำเลย ({len(unique_groups)} กลุ่ม) ===")
